def filled_runs(row: str) -> Iterator[tuple[int, int]]:
    for start, cell in enumerate(row):
        if cell == "#" and (start == 0 or row[start - 1] == "."):
            stop = row.find(".", start)
            yield start, len(row) if stop == -1 else stop


def danmaku():
    designs = {}
    for char, pattern in PATTERNS.items():
        rows = pattern.split("/")
        paths = []
        for row, cells in enumerate(rows):
            for col, cell in enumerate(cells):
                if cell == ".":
                    continue
                x, y = 80 + col * 99, 40 + (6 - row) * 103
                if (row + col * 2) % 5 == 0:
                    paths.append(
                        f"M{x} {y+40} L{x+15} {y+15} L{x+40} {y} "
                        f"L{x+15} {y-15} L{x} {y-40} L{x-15} {y-15} "
                        f"L{x-40} {y} L{x-15} {y+15} Z"
                    )
                else:
                    r = 32 if (row + col) % 2 else 36
                    paths.append(
                        f"M{x} {y+r} Q{x+r} {y+r} {x+r} {y} "
                        f"Q{x+r} {y-r} {x} {y-r} Q{x-r} {y-r} {x-r} {y} "
                        f"Q{x-r} {y+r} {x} {y+r} Z"
                    )
        designs[char] = (160 + 99 * (len(rows[0]) - 1), *paths)
    return designs


def gap():
    designs = {}
    for char, pattern in PATTERNS.items():
        rows = pattern.split("/")
        paths = []
        for row, cells in enumerate(rows):
            shift = 102 if row < 3 else 0
            top = 705 - 96 * row - (33 if row >= 3 else 0)
            bottom = top - 83
            for start, stop in filled_runs(cells):
                left = 38 + start * 94 + shift
                right = 26 + stop * 94 + shift
                paths.append(
                    f"M{left} {bottom} L{right-18} {bottom} "
                    f"L{right} {top} L{left+18} {top} Z"
                )
        designs[char] = (94 * len(rows[0]) + 145, *paths)
    return designs


