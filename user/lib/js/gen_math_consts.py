#!/usr/bin/env python3
"""Derives the constants of user/lib/js/src/jsmath.c from first principles with Python's decimal arithmetic.

    python3 user/lib/js/gen_math_consts.py > user/lib/js/src/math_consts.h

pi comes from Machin's formula (pi = 16 atan(1/5) - 4 atan(1/239)), logarithms from the atanh series
(ln x = 2 atanh((x-1)/(x+1))), arctangents from their Taylor series; nothing is copied from another library.
Each constant is printed as the nearest double (hi) plus the nearest double to the rest (lo), or as exact chunks.
"""
from decimal import Decimal, getcontext
import struct

getcontext().prec = 480          # decimal digits: about 1590 bits


def atan_inv(n):
    """atan(1/n) for an integer n > 1."""
    x = Decimal(1) / n
    x2 = x * x
    term, total, k = x, Decimal(0), 0
    eps = Decimal(10) ** -(getcontext().prec - 5)
    while abs(term) > eps:
        total += term / (2 * k + 1) if k % 2 == 0 else -term / (2 * k + 1)
        term *= x2
        k += 1
    return total


def atan_series(x):
    """atan(x) for |x| < 1 (Euler's accelerated form converges fast for any |x| <= 1)."""
    x = Decimal(x)
    y = x * x / (1 + x * x)
    term = x / (1 + x * x)
    total, k = Decimal(0), 0
    eps = Decimal(10) ** -(getcontext().prec - 5)
    while abs(term) > eps:
        total += term
        k += 1
        term = term * y * (2 * k) / (2 * k + 1)
    return total


def atanh(x):
    x = Decimal(x)
    x2 = x * x
    term, total, k = x, Decimal(0), 0
    eps = Decimal(10) ** -(getcontext().prec - 5)
    while abs(term) > eps:
        total += term / (2 * k + 1)
        term *= x2
        k += 1
    return total


PI = 16 * atan_inv(5) - 4 * atan_inv(239)
LN2 = 2 * atanh(Decimal(1) / 3)
LN10 = 2 * atanh(Decimal(9) / 11)


def hexf(d):
    return "0x%016xULL" % struct.unpack("<Q", struct.pack("<d", d))[0]


def hilo(name, v):
    hi = float(v)
    lo = float(v - Decimal(hi))
    print("#define %s_HI %s   /* %r */" % (name, hexf(hi), hi))
    print("#define %s_LO %s   /* %r */" % (name, hexf(lo), lo))


def chunks(name, v, bits=33, n=3):
    """v as n doubles: the first n-1 hold `bits` significant bits each (so that small multiples are exact)."""
    rest = v
    e = 0
    while Decimal(2) ** (e + 1) <= abs(v):
        e += 1
    while Decimal(2) ** e > abs(v):
        e -= 1
    pos = bits - 1 - e                  # bits after the binary point in the first chunk
    for i in range(n):
        if i < n - 1:
            scale = Decimal(2) ** pos
            c = (rest * scale).to_integral_value(rounding="ROUND_FLOOR") / scale
            pos += bits
        else:
            c = Decimal(float(rest))
        f = float(c)
        assert Decimal(f) == c, "chunk not exact"
        print("#define %s_%d %s   /* %r */" % (name, i + 1, hexf(f), f))
        rest -= c


print("/* Generated by user/lib/js/gen_math_consts.py: do not edit. */")
hilo("KZ_PI", PI)
hilo("KZ_PIO2", PI / 2)
hilo("KZ_PIO4", PI / 4)
hilo("KZ_LN2", LN2)
hilo("KZ_INV_LN2", 1 / LN2)
hilo("KZ_INV_LN10", 1 / LN10)
hilo("KZ_LOG10_2", LN2 / LN10)
hilo("KZ_ATAN_HALF", atan_series(Decimal("0.5")))
hilo("KZ_ATAN_ONE", PI / 4)
hilo("KZ_ATAN_THREEHALF", PI / 2 - atan_series(Decimal(2) / 3))
chunks("KZ_PIO2_C", PI / 2)
chunks("KZ_LN2_C", LN2, bits=32, n=2)


def table(name, values):
    print("static const double %s[%d][2] = {" % (name, len(values)))
    for v in values:
        hi = float(v)
        lo = float(v - Decimal(hi))
        print("    { %r, %r }," % (hi, lo))
    print("};")


table("kz_inv_odd", [Decimal(1) / (2 * n + 1) for n in range(24)])
fact = [Decimal(1)]
for n in range(1, 13):
    fact.append(fact[-1] * n)
table("kz_inv_fact", [1 / f for f in fact])
# the bits of 2/pi after the binary point, 32 per word, enough for any double exponent plus a 192-bit window
two_over_pi = 2 / PI
words = []
frac = two_over_pi
for i in range(48):
    frac *= 2 ** 32
    w = int(frac)
    words.append(w)
    frac -= w
print("static const uint32_t kz_two_over_pi[%d] = {" % len(words))
for i in range(0, len(words), 6):
    print("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
print("};")
