#!/usr/bin/env python3
"""Generates user/lib/web/src/entities.c, the HTML named character references table, from the WHATWG specification's
entities.json (https://html.spec.whatwg.org/entities.json, the table of section 13.5 in machine-readable form).

    curl -o build/web-fetch/entities/entities.json https://html.spec.whatwg.org/entities.json
    python3 -I user/lib/web/gen/genentities.py build/web-fetch/entities/entities.json user/lib/web/src/entities.c

The names are sorted by bytes so that the tokenizer can narrow the candidates character by character with binary searches
(tokenizer.c, "named character reference state"); all names are concatenated into one string to keep the table small.
"""
import json
import sys


def main(src, dst):
    table = json.load(open(src, encoding="utf-8"))
    entries = []
    for name, v in table.items():
        assert name.startswith("&")
        cps = v["codepoints"]
        assert 1 <= len(cps) <= 2, name
        entries.append((name[1:].encode("ascii"), cps))
    entries.sort(key=lambda e: e[0])
    pool = b"".join(e[0] for e in entries)
    assert len(pool) < 65536
    out = []
    out.append("/* GENERATED by user/lib/web/gen/genentities.py from the WHATWG entities.json -- do not edit by hand.")
    out.append(" * The named character references of the HTML standard (section 13.5): %d names, sorted by bytes. */" % len(entries))
    out.append('#include "webint.h"')
    out.append("")
    out.append("const char web_entity_names[] =")
    line = ""
    for name, _ in entries:
        s = name.decode("ascii")
        if len(line) + len(s) > 100:
            out.append('    "%s"' % line)
            line = ""
        line += s
    if line:
        out.append('    "%s"' % line)
    out[-1] += ";"
    out.append("")
    out.append("const WebEntity web_entities[] = {")
    off = 0
    for name, cps in entries:
        cp2 = cps[1] if len(cps) > 1 else 0
        out.append("    { %d, %d, %d, { 0x%X, 0x%X } },  /* %s */" % (off, len(name), len(cps), cps[0], cp2, name.decode("ascii")))
        off += len(name)
    out.append("};")
    out.append("")
    out.append("const int web_entity_count = %d;" % len(entries))
    out.append("")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("%d entities, %d bytes of names" % (len(entries), len(pool)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
