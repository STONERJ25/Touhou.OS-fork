#!/usr/bin/env python3
"""Generates user/lib/web/src/jistables.c (the JIS X 0208 and JIS X 0212 indexes of the WHATWG Encoding standard, used by the
Shift_JIS and EUC-JP decoders in encoding.c) from the standard's index files:

    curl -o build/web-fetch/encoding/index-jis0208.txt https://encoding.spec.whatwg.org/index-jis0208.txt
    curl -o build/web-fetch/encoding/index-jis0212.txt https://encoding.spec.whatwg.org/index-jis0212.txt
    python3 -I user/lib/web/gen/genjis.py build/web-fetch/encoding user/lib/web/src/jistables.c

Each index maps a pointer to a code point; the tables are dense arrays indexed by pointer, 0 where the index has no entry.
"""
import os
import sys


def read_index(path):
    table = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        ptr, cp = line.split()[:2]
        table[int(ptr)] = int(cp, 16)
    return table


def emit(out, name, table):
    n = max(table) + 1
    assert all(cp <= 0xFFFF for cp in table.values()), name
    out.append("const uint16_t %s[%d] = {" % (name, n))
    row = []
    for p in range(n):
        row.append("0x%04X" % table.get(p, 0))
        if len(row) == 12:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("};")
    out.append("const int %s_count = %d;" % (name, n))
    out.append("")


def main(src, dst):
    j208 = read_index(os.path.join(src, "index-jis0208.txt"))
    j212 = read_index(os.path.join(src, "index-jis0212.txt"))
    out = ["/* GENERATED by user/lib/web/gen/genjis.py from the WHATWG Encoding standard's index-jis0208.txt and",
           " * index-jis0212.txt -- do not edit by hand. Pointer -> code point, 0 = no entry. */",
           "#include <stdint.h>", ""]
    emit(out, "web_jis0208", j208)
    emit(out, "web_jis0212", j212)
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("jis0208: %d entries (%d pointers), jis0212: %d entries (%d pointers)" % (len(j208), max(j208) + 1, len(j212), max(j212) + 1))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
