"""The os module: a directory tree (walk, scandir, stat, rename, links, times), descriptors (open flags, dup, pread, truncate, pipes), errors and their errno values,
and processes (fork, wait, exec, kill, spawn). Everything is made in the working directory and printed in a fixed order."""
import errno
import os
import signal
import stat
import sys


def show(label, value=""):
    print(f"{label}: {value}")


def err(label, fn, *args):
    try:
        r = fn(*args)
        show(label, f"no error ({r!r})")
    except OSError as e:
        show(label, f"{type(e).__name__} errno={errno.errorcode.get(e.errno, e.errno)} {e.strerror}")


os.umask(0o022)

print("--- a tree")
os.makedirs("tree/a/b/c")
os.makedirs("tree/d")
for name, text in [("tree/top.txt", "top\n"), ("tree/a/one.txt", "one\n" * 3), ("tree/a/b/two.bin", "\x00\x01\x02"), ("tree/a/b/c/deep.txt", "deep"), ("tree/d/empty", "")]:
    with open(name, "w") as f:
        f.write(text)
for dirpath, dirnames, filenames in os.walk("tree"):
    dirnames.sort()
    show(dirpath, f"dirs={dirnames} files={sorted(filenames)}")
show("bottom-up", [d for d, _, _ in os.walk("tree", topdown=False)])
show("listdir", sorted(os.listdir("tree")))
with os.scandir("tree/a") as it:
    show("scandir", sorted((e.name, e.is_dir(), e.is_file(), e.is_symlink()) for e in it))
st = os.stat("tree/a/one.txt")
show("stat", (st.st_size, stat.S_ISREG(st.st_mode), stat.filemode(st.st_mode), st.st_nlink, st.st_mtime > 1_000_000_000, st.st_blksize > 0))
show("dir mode", stat.filemode(os.stat("tree/a").st_mode))
os.chmod("tree/a/one.txt", 0o600)
show("chmod", oct(os.stat("tree/a/one.txt").st_mode & 0o777))
os.rename("tree/top.txt", "tree/renamed.txt")
show("rename", (os.path.exists("tree/top.txt"), os.path.exists("tree/renamed.txt")))
os.replace("tree/renamed.txt", "tree/d/empty")
show("replace", (os.path.exists("tree/renamed.txt"), open("tree/d/empty").read()))
os.symlink("a/one.txt", "tree/link")
show("symlink", (os.readlink("tree/link"), os.path.islink("tree/link"), os.path.exists("tree/link"), open("tree/link").read().count("one")))
os.symlink("nowhere", "tree/dangling")
show("dangling", (os.path.islink("tree/dangling"), os.path.exists("tree/dangling"), stat.S_ISLNK(os.lstat("tree/dangling").st_mode)))
os.link("tree/a/one.txt", "tree/hard")
show("hard link", (os.stat("tree/hard").st_nlink, os.path.samefile("tree/hard", "tree/a/one.txt")))
os.utime("tree/a/one.txt", (1_000_000_000, 1_500_000_000))
show("utime", (int(os.stat("tree/a/one.txt").st_atime), int(os.stat("tree/a/one.txt").st_mtime)))
os.truncate("tree/a/one.txt", 5)
show("truncate", (os.path.getsize("tree/a/one.txt"), open("tree/a/one.txt").read()))
show("realpath", os.path.relpath(os.path.realpath("tree/link"), os.getcwd()))
show("access", (os.access("tree", os.F_OK), os.access("tree/a/one.txt", os.R_OK), os.access("nothing", os.F_OK)))
os.chdir("tree/a/b")
show("chdir", os.path.relpath(os.getcwd(), os.path.dirname(os.path.dirname(os.path.dirname(os.getcwd())))))
show("relative", (os.path.exists("../one.txt"), os.path.exists("c/deep.txt"), os.listdir("c")))
os.chdir("../../..")
os.remove("tree/dangling")
os.rmdir("tree/a/b/c") if not os.listdir("tree/a/b/c") else os.remove("tree/a/b/c/deep.txt")
os.rmdir("tree/a/b/c")
show("rmdir", os.listdir("tree/a/b"))

print("--- errors")
err("open missing", open, "nothing/at/all")
err("mkdir exists", os.mkdir, "tree")
err("rmdir not empty", os.rmdir, "tree")
err("rmdir a file", os.rmdir, "tree/hard")
err("listdir a file", os.listdir, "tree/hard")
err("open a directory", lambda: open("tree").read())
err("unlink a directory", os.unlink, "tree/a")
err("readlink a file", os.readlink, "tree/hard")
err("symlink exists", os.symlink, "x", "tree/hard")
err("stat missing", os.stat, "tree/missing")
err("rename missing", os.rename, "tree/missing", "tree/other")
err("bad descriptor", os.read, 999, 1)
err("close twice", lambda: (os.close(os.dup(0)), os.close(997)))
err("long name", os.stat, "x" * 300)
err("not a directory", os.stat, "tree/hard/inside")
err("link loop", lambda: (os.symlink("loop2", "loop1"), os.symlink("loop1", "loop2"), os.stat("loop1")))
err("seek on a pipe", lambda: os.lseek(os.pipe()[0], 0, os.SEEK_SET))
err("write to a read end", lambda: os.write(os.pipe()[0], b"x"))

print("--- descriptors")
fd = os.open("data.bin", os.O_RDWR | os.O_CREAT | os.O_EXCL, 0o644)
show("write", os.write(fd, b"0123456789abcdef"))
show("lseek", (os.lseek(fd, 4, os.SEEK_SET), os.read(fd, 4), os.lseek(fd, 0, os.SEEK_CUR), os.lseek(fd, -2, os.SEEK_END), os.read(fd, 10)))
show("pread", (os.pread(fd, 3, 10), os.lseek(fd, 0, os.SEEK_CUR)))
show("pwrite", (os.pwrite(fd, b"XY", 1), os.pread(fd, 6, 0)))
os.ftruncate(fd, 8)
show("ftruncate", (os.fstat(fd).st_size, os.pread(fd, 20, 0)))
os.fsync(fd)
d2 = os.dup(fd)
os.lseek(fd, 2, os.SEEK_SET)
show("dup shares the offset", (os.read(d2, 2), os.get_inheritable(d2), os.get_inheritable(fd)))
os.set_inheritable(d2, True)
show("inheritable", (os.get_inheritable(d2), os.get_blocking(d2)))
os.close(d2)
err("O_EXCL", os.open, "data.bin", os.O_CREAT | os.O_EXCL | os.O_WRONLY)
fa = os.open("data.bin", os.O_WRONLY | os.O_APPEND)
os.write(fa, b"++")
show("append", os.pread(fd, 20, 0))
os.close(fa)
ft = os.open("data.bin", os.O_WRONLY | os.O_TRUNC)
show("O_TRUNC", os.fstat(ft).st_size)
os.close(ft)
os.close(fd)
show("O_DIRECTORY", stat.S_ISDIR(os.fstat(os.open("tree", os.O_RDONLY | os.O_DIRECTORY)).st_mode))
err("O_NOFOLLOW", os.open, "tree/link", os.O_RDONLY | os.O_NOFOLLOW)
with open("text.txt", "w", encoding="utf-8") as f:
    f.write("héllo\nwörld\n")
with open("text.txt", "rb") as f:
    show("utf-8 bytes", f.read())
with open("text.txt", encoding="utf-8") as f:
    show("lines", f.readlines())
with open("text.txt", "r+", encoding="utf-8") as f:
    f.seek(0, 2)
    f.write("end")
    f.seek(0)
    show("r+", (f.read(), f.tell()))
r, w = os.pipe()
show("pipe", (os.write(w, b"through a pipe"), os.read(r, 100)))
os.close(w)
show("end of file", os.read(r, 100))
os.set_blocking(r, False)
os.close(r)
r, w = os.pipe()
os.set_blocking(r, False)
err("nonblocking read", os.read, r, 1)
os.close(w)
r, w = os.pipe()
show("writev", os.writev(w, [b"ab", b"cd", b"ef"]))
b1, b2 = bytearray(2), bytearray(4)
show("readv", (os.readv(r, [b1, b2]), bytes(b1), bytes(b2)))
show("fstat of a pipe", stat.S_ISFIFO(os.fstat(r).st_mode))
os.close(r)
os.close(w)
show("isatty", (os.isatty(0), os.isatty(1)))
err("terminal size", os.get_terminal_size)
show("devnull", (os.write(os.open(os.devnull, os.O_WRONLY), b"gone"), len(os.read(os.open("/dev/zero", os.O_RDONLY), 16)), len(os.urandom(16)), len(os.getrandom(8))))
st = os.statvfs(".")
show("statvfs", (st.f_bsize > 0, st.f_namemax > 0))
show("uname", (os.uname().sysname, os.uname().machine))
show("environ copy", sorted(os.environ.copy()) == sorted(os.environ))
os.putenv("OSOPS_X", "1")
os.environ["OSOPS_Y"] = "2"
show("environ", (os.environ.get("OSOPS_Y"), os.getenv("OSOPS_X"), os.getenv("OSOPS_NONE", "default")))
show("get_exec_path", os.get_exec_path())
show("cpu", (os.cpu_count() >= 1, len(os.sched_getaffinity(0)) >= 1))
show("times", all(v >= 0 for v in os.times()[:4]))
show("ids", (os.getpid() > 0, os.getppid() >= 0, os.getpgrp() > 0, os.getsid(0) > 0, os.getuid() >= 0, os.getgid() >= 0))
show("getlogin/umask", (os.umask(0o077), os.umask(0o022)))
show("nice", (os.nice(0), os.getpriority(os.PRIO_PROCESS, 0), os.nice(2), os.getpriority(os.PRIO_PROCESS, 0), os.nice(0)))
# the directories of the machine itself are directories (on this system /tmp is a link underneath: a program must never see that, SQLite resolves every component of a path)
show("system directories", [(d, stat.S_ISDIR(os.lstat(d).st_mode), os.path.islink(d), os.path.realpath(d)) for d in ("/tmp", "/dev", "/proc", "/sys", "/run")])
show("a path through /tmp", (os.path.realpath(os.path.join("/tmp", "..", "tmp")), os.path.isdir("/tmp/.")))

print("--- fork, wait, exit statuses")
pid = os.fork()
if pid == 0:
    os._exit(7)
_, status = os.waitpid(pid, 0)
show("exit 7", (os.WIFEXITED(status), os.WEXITSTATUS(status), os.WIFSIGNALED(status)))
pid = os.fork()
if pid == 0:
    os.kill(os.getpid(), signal.SIGKILL)
    os._exit(0)
_, status = os.waitpid(pid, 0)
show("killed", (os.WIFEXITED(status), os.WIFSIGNALED(status), os.WTERMSIG(status)))
pid = os.fork()
if pid == 0:
    signal.pause()
    os._exit(0)
os.kill(pid, signal.SIGTERM)
_, status = os.waitpid(pid, 0)
show("terminated", (os.WIFSIGNALED(status), os.WTERMSIG(status)))
err("wait without children", os.wait)
r, w = os.pipe()
pid = os.fork()
if pid == 0:
    os.close(r)
    os.write(w, f"child says {os.getppid() > 0}".encode())
    os._exit(0)
os.close(w)
show("through the fork", os.read(r, 100))
os.waitpid(pid, 0)
os.close(r)
pid = os.fork()
if pid == 0:
    os.write(1, b"child output goes to the shared descriptor\n")
    os._exit(0)
os.waitpid(pid, 0)
pids = []
for n in range(3):
    pid = os.fork()
    if pid == 0:
        os._exit(10 + n)
    pids.append(pid)
done = {}
for _ in range(3):
    pid, status = os.wait()
    done[pids.index(pid)] = os.WEXITSTATUS(status)
show("three children", [done[i] for i in range(3)])
pid = os.fork()
if pid == 0:
    os._exit(3)
pid_w, status, ru = os.wait4(pid, 0)
show("wait4", (pid_w == pid, os.WEXITSTATUS(status), ru.ru_utime >= 0))
pid = os.fork()
if pid == 0:
    os._exit(4)
info = os.waitid(os.P_PID, pid, os.WEXITED)
show("waitid", (info.si_pid == pid, info.si_code == os.CLD_EXITED, info.si_status))
pid = os.fork()
if pid == 0:
    os.setsid()
    os._exit(int(os.getsid(0) == os.getpid()))
_, status = os.waitpid(pid, 0)
show("setsid in the child", os.WEXITSTATUS(status))
r, w = os.pipe()
pid = os.fork()
if pid == 0:
    os.close(r)
    os.dup2(w, 1)
    os.close(w)
    os.execv("/bin/echo", ["echo", "hello from exec", "with", "arguments"])
os.close(w)
show("execv", os.read(r, 100))
show("execv status", os.waitstatus_to_exitcode(os.waitpid(pid, 0)[1]))
pid = os.fork()
if pid == 0:
    os.execve("/usr/bin/env", ["env"], {"ONLY": "this", "PATH": "/usr/bin"})
os.waitpid(pid, 0)
r, w = os.pipe()
pid = os.fork()
if pid == 0:
    os.dup2(w, 1)
    os.execvp("sh", ["sh", "-c", "echo via execvp; exit 5"])
os.close(w)
show("execvp", os.read(r, 100))
show("execvp status", os.waitstatus_to_exitcode(os.waitpid(pid, 0)[1]))
os.close(r)
pid = os.fork()
if pid == 0:
    try:
        os.execv("/nonexistent/program", ["x"])
    except OSError as e:
        os._exit(40 + (e.errno == errno.ENOENT))
_, status = os.waitpid(pid, 0)
show("exec of a missing file", os.WEXITSTATUS(status))
pid = os.posix_spawn("/bin/true", ["true"], os.environ)
show("posix_spawn", os.waitstatus_to_exitcode(os.waitpid(pid, 0)[1]))
pid = os.posix_spawnp("sh", ["sh", "-c", "exit 9"], os.environ)
show("posix_spawnp", os.waitstatus_to_exitcode(os.waitpid(pid, 0)[1]))
show("system", (os.system("exit 3") >> 8, os.system("true"), os.system("echo from system")))
show("popen", os.popen("echo popen output; echo second").read())
with os.popen("exit 2") as p:
    p.read()
show("popen close", p.close())
sys.stdout.flush()
print("--- done")
