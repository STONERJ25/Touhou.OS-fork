void hid_parser_selftest(void) {
    int total = 0, failed = 0;
#define CHECK(cond) do { total++; if (!(cond)) { failed++; klog("Satori", "hid parser self test: FAILED at line %d: %s", __LINE__, #cond); } } while (0)
    HidParsed *p = kmalloc(sizeof *p);
    HidMouseMap mm;
    HidKbdMap km;
    int dx, dy, wh;
    u8 b, cur[32];
    if (!p) return;

    hid_parse(d_logitech, sizeof d_logitech, p);
    CHECK(find_mouse(p, &mm) && mm.use_id && mm.id == 2);
    CHECK(mm.x.off == 16 && mm.x.size == 12 && mm.y.off == 28 && mm.y.size == 12 && mm.has_wheel && mm.wheel.off == 40 && mm.wheel.size == 8);
    CHECK(mm.has_btn[0] && mm.has_btn[1] && mm.has_btn[2] && mm.btn_off[0] == 0 && mm.btn_off[1] == 1 && mm.btn_off[2] == 2 && mm.need_bits == 48);
    {
        const u8 r[] = { 0x02, 0x05, 0x00, 0xFD, 0x4F, 0x06, 0xFF, 0x00 };
        CHECK(mouse_decode(&mm, r, sizeof r, &dx, &dy, &wh, &b) && dx == -3 && dy == 100 && wh == -1 && b == 5);
    }
    {
        const u8 r[] = { 0x03, 0x05, 0x00, 0xFD, 0x4F, 0x06, 0xFF, 0x00 };          /* another report id */
        CHECK(!mouse_decode(&mm, r, sizeof r, &dx, &dy, &wh, &b));
    }
    {
        const u8 r[] = { 0x02, 0x05, 0x00 };                                         /* truncated */
        CHECK(!mouse_decode(&mm, r, sizeof r, &dx, &dy, &wh, &b));
    }

    hid_parse(d_gaming, sizeof d_gaming, p);
    CHECK(find_mouse(p, &mm) && !mm.use_id && mm.x.off == 8 && mm.x.size == 16 && mm.y.off == 24 && mm.y.size == 16 && mm.wheel.off == 40);
    {
        const u8 r[] = { 0x03, 0xE8, 0x03, 0xFE, 0xFF, 0x01 };
        CHECK(mouse_decode(&mm, r, sizeof r, &dx, &dy, &wh, &b) && dx == 1000 && dy == -2 && wh == 1 && b == 3);
    }

    hid_parse(d_plain, sizeof d_plain, p);
    CHECK(find_mouse(p, &mm) && !mm.use_id && mm.x.off == 8 && mm.y.off == 16 && mm.wheel.off == 24 && mm.need_bits == 32);
    {
        const u8 r[] = { 0x01, 0x05, 0xFB, 0xFF };
        CHECK(mouse_decode(&mm, r, sizeof r, &dx, &dy, &wh, &b) && dx == 5 && dy == -5 && wh == -1 && b == 1);
    }

    hid_parse(d_tablet, sizeof d_tablet, p);
    CHECK(!find_mouse(p, &mm));

    hid_parse(d_kbd, sizeof d_kbd, p);
    CHECK(find_keyboard(p, &km) && !km.use_id && km.mod_off[0] == 0 && km.mod_off[7] == 7 && km.narr == 1);
    CHECK(km.arr[0].off == 16 && km.arr[0].size == 8 && km.arr[0].count == 6);
    CHECK(km.led_known && km.led_off[0] == 0 && km.led_off[1] == 1 && km.led_off[2] == 2 && km.led_bytes == 1);
    {
        const u8 r[] = { 0x02, 0x00, 0x04, 0x05, 0, 0, 0, 0 };
        CHECK(kbd_decode(&km, r, sizeof r, cur) && bit_get(cur, 0xE1) && bit_get(cur, 4) && bit_get(cur, 5) && !bit_get(cur, 6) && !bit_get(cur, 0xE0));
    }
    {
        const u8 r[] = { 0, 0, 1, 1, 1, 1, 1, 1 };                                   /* ErrorRollOver in every slot */
        CHECK(!kbd_decode(&km, r, sizeof r, cur));
    }

    hid_parse(d_kbd_ids, sizeof d_kbd_ids, p);
    CHECK(find_keyboard(p, &km) && km.use_id && km.id == 1 && km.arr[0].off == 16 && km.led_known && km.led_id == 1 && km.led_bytes == 1);
    {
        const u8 r[] = { 0x01, 0x01, 0x00, 0x06, 0, 0, 0, 0, 0 };
        CHECK(kbd_decode(&km, r, sizeof r, cur) && bit_get(cur, 0xE0) && bit_get(cur, 6));
    }
    {
        const u8 r[] = { 0x02, 0x03, 0x00 };                                         /* the consumer collection's report */
        CHECK(!kbd_decode(&km, r, sizeof r, cur));
    }

    hid_parse(d_nkro, sizeof d_nkro, p);
    CHECK(!find_keyboard(p, &km));

    /* Truncated descriptors must not crash the parser or the finders. */
    const u8 *all[] = { d_logitech, d_gaming, d_plain, d_tablet, d_kbd, d_kbd_ids, d_nkro };
    const size_t lens[] = { sizeof d_logitech, sizeof d_gaming, sizeof d_plain, sizeof d_tablet, sizeof d_kbd, sizeof d_kbd_ids, sizeof d_nkro };
    for (unsigned i = 0; i < ARRAY_SIZE(all); i++)
        for (size_t cut = 0; cut <= lens[i]; cut++) {
            hid_parse(all[i], (int)cut, p);
            find_mouse(p, &mm);
            find_keyboard(p, &km);
        }
    CHECK(true);
#undef CHECK
    kfree(p);
    klog("Satori", "hid parser self test: %d checks, %d failed", total, failed);
}
