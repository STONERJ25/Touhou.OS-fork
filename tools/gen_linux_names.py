#!/usr/bin/env python3
"""Writes kernel/linux/names.inc: the names of the x86-64 Linux system calls by number, for the log line of a call the Linux personality does not implement.

    wsl.exe -e python3 tools/gen_linux_names.py          (runs on a Linux: it reads the number list that a Linux publishes for programs)

The input is the list of "name = number" pairs from <asm/unistd_64.h>, the file every program and every libc reads to learn the numbers; it is the interface, not an
implementation, and only the pairs are used. The numbers the kernel actually relies on are in kernel/linux/numbers.h and are checked against a running Linux
by tests/host/test_linux_abi.py. Nothing here decides behaviour: a wrong or missing name only makes a log line less helpful.
"""
import re
import sys
from pathlib import Path

HEADERS = ["/usr/include/x86_64-linux-gnu/asm/unistd_64.h", "/usr/include/asm/unistd_64.h"]
OUT = Path(__file__).resolve().parent.parent / "kernel" / "linux" / "names.inc"


def main():
    src = next((Path(h) for h in HEADERS if Path(h).is_file()), None)
    if not src:
        sys.exit("gen_linux_names: no unistd_64.h found (run this on a Linux: wsl.exe -e python3 tools/gen_linux_names.py)")
    pairs = {}
    for line in src.read_text().splitlines():
        m = re.match(r"#define __NR_([a-z0-9_]+)\s+(\d+)\s*$", line)
        if m and int(m.group(2)) < 1000:
            pairs[int(m.group(2))] = m.group(1)
    lines = ["/* GENERATED by tools/gen_linux_names.py -- do not edit. Names of the x86-64 Linux system calls by number (log lines only). */"]
    lines += [f'[{n}] = "{name}",' for n, name in sorted(pairs.items())]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"gen_linux_names: {len(pairs)} names, highest number {max(pairs)}, written to {OUT}")


if __name__ == "__main__":
    main()
