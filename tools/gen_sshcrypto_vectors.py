#!/usr/bin/env python3
"""Writes user/bin/sshkat_vectors.h: known-answer vectors for user/lib/sshcrypto, made with Python's `cryptography` package and hashlib (which share no
code with it) from a fixed seed, plus the RFC 7748 / RFC 8032 / RFC 8439 vectors. The guest program user/bin/sshkat.c checks them; tests/case_sshcrypto.py runs it.

    python tools/gen_sshcrypto_vectors.py        (needs `cryptography`; the output is committed, regenerate only when the set should change)
"""
import hashlib
import random
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.poly1305 import Poly1305

OUT = Path(__file__).resolve().parent.parent / "user" / "bin" / "sshkat_vectors.h"
rng = random.Random(25519)


def rb(n):
    return bytes(rng.getrandbits(8) for _ in range(n))


def hx(b):
    return b.hex()


L = 2**252 + 27742317777372353535851937790883648493
out = ["/* GENERATED by tools/gen_sshcrypto_vectors.py -- do not edit. */", ""]

# SHA-512: lengths around the block and padding boundaries
msgs = [b"", b"abc"] + [b"a" * n for n in (111, 112, 113, 127, 128, 129, 239, 240, 255, 256)] + [rb(1000), rb(4097)]
out.append("static const struct { const char *msg, *digest; } sha512_v[] = {")
for m in msgs:
    out.append(f'    {{ "{hx(m)}", "{hashlib.sha512(m).hexdigest()}" }},')
out += ["};", ""]

# X25519: RFC 7748 vectors, then random ones
out.append("static const struct { const char *scalar, *point, *out; } x25519_v[] = {")
rfc = [("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4", "e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c",
        "c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552"),
       ("4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d", "e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493",
        "95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957")]
for s, p, o in rfc:
    out.append(f'    {{ "{s}", "{p}", "{o}" }},')
for _ in range(10):
    sk = rb(32)
    pub = X25519PrivateKey.from_private_bytes(rb(32)).public_key().public_bytes_raw()
    shared = X25519PrivateKey.from_private_bytes(sk).exchange(X25519PublicKey.from_public_bytes(pub))
    out.append(f'    {{ "{hx(sk)}", "{hx(pub)}", "{hx(shared)}" }},')
out += ["};", ""]
out.append("static const struct { const char *scalar, *pub; } x25519_base_v[] = {")
for sk in [bytes.fromhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a"),
           bytes.fromhex("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")] + [rb(32) for _ in range(8)]:
    out.append(f'    {{ "{hx(sk)}", "{hx(X25519PrivateKey.from_private_bytes(sk).public_key().public_bytes_raw())}" }},')
out += ["};", ""]

# Ed25519: RFC 8032 and random keys and messages; every entry also gets a corrupted signature in the guest program
out.append("static const struct { const char *seed, *pk, *msg, *sig; } ed25519_v[] = {")
cases = [(bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60"), b""),
         (bytes.fromhex("4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb"), bytes.fromhex("72"))]
for n in (0, 1, 31, 32, 33, 64, 100, 250, 600):
    cases.append((rb(32), rb(n)))
for seed, msg in cases:
    key = Ed25519PrivateKey.from_private_bytes(seed)
    out.append(f'    {{ "{hx(seed)}", "{hx(key.public_key().public_bytes_raw())}", "{hx(msg)}", "{hx(key.sign(msg))}" }},')
out += ["};", ""]
seed, msg = rb(32), b"hello"
key = Ed25519PrivateKey.from_private_bytes(seed)
sig = key.sign(msg)
twin = sig[:32] + (int.from_bytes(sig[32:], "little") + L).to_bytes(33, "little")[:32]
out.append("/* the same signature with S + L: valid arithmetic, but S is not below the group order, so it must be refused */")
out.append(f'static const struct {{ const char *pk, *msg, *sig; }} ed25519_twin = {{ "{hx(key.public_key().public_bytes_raw())}", "{hx(msg)}", "{hx(twin)}" }};')
out.append("")

# ChaCha20 with a 64-bit nonce and a 64-bit counter (counters below 2^32 are the same as the IETF layout with a zero high word)
out.append("static const struct { const char *key, *nonce; unsigned long long counter; const char *in, *out; } chacha_v[] = {")
for n in (0, 1, 63, 64, 65, 200, 1000):
    key, nonce, data = rb(32), rb(8), rb(n)
    counter = rng.choice([0, 1, 7, 2**32 - 1])
    iv = (counter % 2**32).to_bytes(4, "little") + (counter // 2**32).to_bytes(4, "little") + nonce
    enc = Cipher(algorithms.ChaCha20(key, iv), mode=None).encryptor()
    out.append(f'    {{ "{hx(key)}", "{hx(nonce)}", {counter}ULL, "{hx(data)}", "{hx(enc.update(data) + enc.finalize())}" }},')
out += ["};", ""]

# Poly1305: RFC 8439 2.5.2, random, and keys and messages at the edges of the arithmetic
out.append("static const struct { const char *key, *msg, *tag; } poly_v[] = {")
k0 = bytes.fromhex("85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b")
m0 = b"Cryptographic Forum Research Group"
out.append(f'    {{ "{hx(k0)}", "{hx(m0)}", "{Poly1305.generate_tag(k0, m0).hex()}" }},')
for n in (0, 1, 15, 16, 17, 31, 32, 33, 64, 100, 1000, 4096):
    k, m = rb(32), rb(n)
    out.append(f'    {{ "{hx(k)}", "{hx(m)}", "{Poly1305.generate_tag(k, m).hex()}" }},')
for k in (bytes([0xff] * 32), bytes([0xff] * 16) + bytes(16), bytes(16) + bytes([0xff] * 16)):
    for n in (16, 33, 48):
        m = bytes([0xff] * n)
        out.append(f'    {{ "{hx(k)}", "{hx(m)}", "{Poly1305.generate_tag(k, m).hex()}" }},')
out += ["};", ""]
OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
print("wrote", OUT, OUT.stat().st_size, "bytes")
