#!/usr/bin/env python3
"""Writes user/lib/tls/src/tables.h: constants that are better computed than remembered.

  * SHA-512/384 round constants and initial values (fractional parts of cube and square roots of the first primes),
  * the SHA-256 initial values,
  * the parameters of NIST P-256 and P-384 (taken from OpenSSL's explicit parameter dump, checked for consistency),
  * the AES S-box (computed from the field arithmetic, not typed in).

Run:  python tools/gen_tls_tables.py        (needs the `openssl` command; Git for Windows ships one)
The output is committed, so nobody needs to run this to build the system.
"""
import math
import re
import shutil
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "user" / "lib" / "tls" / "src" / "tables.h"


def primes(n):
    out, k = [], 2
    while len(out) < n:
        if all(k % p for p in out if p * p <= k):
            out.append(k)
        k += 1
    return out


def iroot(x, n):
    lo, hi = 0, 1 << ((x.bit_length() // n) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** n <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo


def frac_root(p, n, bits):
    """floor(frac(p ** (1/n)) * 2**bits)"""
    return iroot(p << (bits * n), n) & ((1 << bits) - 1)


def find_openssl():
    for cand in (shutil.which("openssl"), r"C:\Program Files\Git\usr\bin\openssl.exe", r"C:\Program Files\Git\mingw64\bin\openssl.exe"):
        if cand and Path(cand).exists():
            return cand
    sys.exit("gen_tls_tables: no openssl found")


def curve(name):
    text = subprocess.run([find_openssl(), "ecparam", "-name", name, "-param_enc", "explicit", "-text", "-noout"],
                          capture_output=True, text=True, check=True).stdout
    def block(label):
        m = re.search(label + r":\s*((?:\s+[0-9a-f:]+\n?)+)", text)
        return int(re.sub(r"[^0-9a-f]", "", m.group(1)), 16)
    p, a, b, n = block("Prime"), block("A"), block("B"), block("Order")
    g = re.search(r"Generator \(uncompressed\):\s*((?:\s+[0-9a-f:]+\n?)+)", text).group(1)
    g = re.sub(r"[^0-9a-f]", "", g)
    assert g[:2] == "04"
    half = (len(g) - 2) // 2
    gx, gy = int(g[2:2 + half], 16), int(g[2 + half:], 16)
    assert a == p - 3, "the code assumes a = -3"
    assert (gy * gy - (gx ** 3 + a * gx + b)) % p == 0, "generator is not on the curve"
    return dict(p=p, b=b, n=n, gx=gx, gy=gy)


def limbs(v, count):
    return ", ".join(f"0x{(v >> (64 * i)) & ((1 << 64) - 1):016x}ULL" for i in range(count))


def aes_sbox():
    """The AES S-box: multiplicative inverse in GF(2^8) (modulus x^8+x^4+x^3+x+1) followed by the affine map."""
    def rotl8(x, k):
        return ((x << k) | (x >> (8 - k))) & 0xff
    sbox = [0] * 256
    p = q = 1
    while True:
        p = (p ^ (p << 1) ^ (0x1b if p & 0x80 else 0)) & 0xff        # p *= 3
        q ^= (q << 1) & 0xff                                          # q /= 3
        q ^= (q << 2) & 0xff
        q ^= (q << 4) & 0xff
        if q & 0x80:
            q ^= 0x09
        sbox[p] = q ^ rotl8(q, 1) ^ rotl8(q, 2) ^ rotl8(q, 3) ^ rotl8(q, 4) ^ 0x63
        if p == 1:
            break
    sbox[0] = 0x63
    assert sbox[1] == 0x7c and sbox[2] == 0x77 and sbox[0x53] == 0xed and sbox[0xff] == 0x16, "S-box generation is wrong"
    assert len(set(sbox)) == 256
    return sbox


def main():
    pr = primes(80)
    lines = ["/* GENERATED by tools/gen_tls_tables.py -- do not edit. */", "#ifndef TLS_TABLES_H", "#define TLS_TABLES_H", ""]
    lines.append("static const uint64_t TLSC_K512[80] = {")
    for i in range(0, 80, 2):
        lines.append("    " + ", ".join(f"0x{frac_root(pr[j], 3, 64):016x}ULL" for j in (i, i + 1)) + ",")
    lines.append("};")
    lines.append("static const uint64_t TLSC_H512[8] = { " + ", ".join(f"0x{frac_root(pr[i], 2, 64):016x}ULL" for i in range(8)) + " };")
    lines.append("static const uint64_t TLSC_H384[8] = { " + ", ".join(f"0x{frac_root(pr[i], 2, 64):016x}ULL" for i in range(8, 16)) + " };")
    lines.append("static const uint32_t TLSC_H256[8] = { " + ", ".join(f"0x{frac_root(pr[i], 2, 32):08x}U" for i in range(8)) + " };")
    lines.append("static const uint32_t TLSC_K256[64] = {")
    for i in range(0, 64, 4):
        lines.append("    " + ", ".join(f"0x{frac_root(pr[j], 3, 32):08x}U" for j in range(i, i + 4)) + ",")
    lines.append("};")
    sb = aes_sbox()
    lines.append("static const uint8_t TLSC_SBOX[256] = {")
    for i in range(0, 256, 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in sb[i:i + 16]) + ",")
    lines.append("};")
    for name, label, n in (("P256", "prime256v1", 4), ("P384", "secp384r1", 6)):
        c = curve(label)
        lines.append("")
        lines.append(f"/* {label}: little-endian 64-bit limbs; a = p - 3 */")
        for k in ("p", "b", "n", "gx", "gy"):
            lines.append(f"static const uint64_t TLSC_{name}_{k.upper()}[{n}] = {{ {limbs(c[k], n)} }};")
    lines += ["", "#endif", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
