#!/usr/bin/env python3
"""Writes initrd/Hakurei/etc/ssl/certs/ca-bundle.pem: the root certificates TouhouOS trusts for HTTPS.

Source, in order of preference:
  1. Python's `certifi` package, which is Mozilla's root store (what Firefox, and most Linux distributions, trust);
  2. the Windows certificate store ("ROOT"), filtered to roots that are trusted for server authentication. That is
     Microsoft's list, not Mozilla's: the script says so when it has to fall back to it.

Only roots libtls can use go in: RSA keys and the NIST curves P-256 and P-384. Roots that have expired are left out, duplicates
are merged, and the output is sorted so that regenerating it produces small diffs. Every kept root is read back through libtls
itself (tools/tlshost.py) to prove that the bundle loads as a whole.

  python tools/mkcabundle.py            write the bundle
  python tools/mkcabundle.py --check    only report what would be written
  python tools/mkcabundle.py --pem FILE use FILE (a PEM bundle) instead of certifi / the Windows store
"""
import argparse
import base64
import datetime
import hashlib
import re
import ssl
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "initrd" / "Hakurei" / "etc" / "ssl" / "certs" / "ca-bundle.pem"

from cryptography import x509  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec, rsa  # noqa: E402

SERVER_AUTH = "1.3.6.1.5.5.7.3.1"


def from_pem_text(text):
    return [ssl.PEM_cert_to_DER_cert(p) for p in re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", text, re.S)]


def from_certifi():
    import certifi
    return from_pem_text(Path(certifi.where()).read_text(encoding="utf-8")), f"certifi {getattr(certifi, '__version__', '?')} (Mozilla's root store)"


def from_windows():
    if not hasattr(ssl, "enum_certificates"):
        raise RuntimeError("no certifi and not on Windows: give the roots with --pem FILE")
    out = []
    for der, encoding, trust in ssl.enum_certificates("ROOT"):
        if encoding != "x509_asn":
            continue
        if trust is True or (isinstance(trust, (set, frozenset)) and SERVER_AUTH in trust):
            out.append(der)
    return out, "the Windows certificate store (Microsoft's list, NOT Mozilla's)"


def usable(cert, now):
    if cert.not_valid_after_utc < now or cert.not_valid_before_utc > now:
        return "outside its validity period"
    key = cert.public_key()
    if isinstance(key, rsa.RSAPublicKey):
        return None if key.key_size >= 1024 else "RSA key below 1024 bits"
    if isinstance(key, ec.EllipticCurvePublicKey):
        return None if key.curve.name in ("secp256r1", "secp384r1") else f"curve {key.curve.name} is not supported"
    return f"{type(key).__name__} keys are not supported"


def label(cert):
    def attr(oid):
        a = cert.subject.get_attributes_for_oid(oid)
        return a[0].value if a else None
    return (attr(x509.NameOID.COMMON_NAME) or attr(x509.NameOID.ORGANIZATIONAL_UNIT_NAME) or attr(x509.NameOID.ORGANIZATION_NAME) or "unnamed").replace("\n", " ")


def build(ders, source):
    now = datetime.datetime.now(datetime.timezone.utc)
    seen, keep, dropped = set(), [], []
    for der in ders:
        digest = hashlib.sha256(der).digest()
        if digest in seen:
            continue
        seen.add(digest)
        try:
            cert = x509.load_der_x509_certificate(der)
        except Exception as e:  # noqa: BLE001
            dropped.append(("(unparsable)", str(e)))
            continue
        why = usable(cert, now)
        if why:
            dropped.append((label(cert), why))
        else:
            keep.append((label(cert).lower(), label(cert), der))
    keep.sort()
    lines = ["# Root certificates trusted by TouhouOS for HTTPS (libtls, fetch, wget).",
             f"# Source: {source}", f"# Generated by tools/mkcabundle.py on {now.date().isoformat()}: {len(keep)} certificates.",
             "# Use fetch --cacert FILE to trust something else. Do not edit by hand; regenerate.", ""]
    for _, name, der in keep:
        lines.append(f"# {name}")
        b64 = base64.b64encode(der).decode()
        lines.append("-----BEGIN CERTIFICATE-----")
        lines += [b64[i:i + 64] for i in range(0, len(b64), 64)]
        lines.append("-----END CERTIFICATE-----")
    return "\n".join(lines) + "\n", len(keep), dropped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--pem")
    args = ap.parse_args()
    if args.pem:
        ders, source = from_pem_text(Path(args.pem).read_text(encoding="utf-8")), f"{args.pem}"
    else:
        try:
            ders, source = from_certifi()
        except ImportError:
            ders, source = from_windows()
    text, n, dropped = build(ders, source)
    print(f"{len(ders)} certificates read from {source}; {n} kept, {len(dropped)} left out")
    for name, why in dropped:
        print(f"  left out: {name}: {why}")
    print(f"bundle size: {len(text)} bytes")
    if args.check:
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)
    # prove that libtls can read all of it
    sys.path.insert(0, str(ROOT / "tests"))
    import tlslib
    ctx = tlslib.Ctx(text)
    print(f"libtls loaded {ctx.count()} roots ({ctx.skipped()} skipped)")
    if ctx.count() != n:
        print("ERROR: libtls did not accept every certificate that was written", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
